// Package proto defines the protocol shared by hub, daemon, mod and app.
// Types are exported to TypeScript with tygo (see tygo.yaml).
package proto

import "encoding/json"

const Version = "0.1.0"

type SessionState string

const (
	StateWorking  SessionState = "working"
	StateNeedsYou SessionState = "needs_you"
	StateWaiting  SessionState = "waiting"
	StateIdle     SessionState = "idle"
	// StateBackground: the turn ended but background tasks (background Bash, Monitor, background
	// subagents) or a scheduled wake-up (/loop, ScheduleWakeup, CronCreate) are pending.
	StateBackground SessionState = "background"
	StateClosed     SessionState = "closed"
)

type Role string

const (
	RoleWork    Role = "work"
	RoleService Role = "service"
)

type SessionInfo struct {
	ID         string       `json:"id"`
	PreviousID string       `json:"previousId"`
	Machine    string       `json:"machine"`
	Name       string       `json:"name"`
	Cwd        string       `json:"cwd"`
	Root       string       `json:"root"`
	Model      string       `json:"model"`
	Role       Role         `json:"role"`
	State      SessionState `json:"state"`
	ContextPct int          `json:"contextPct"`
	StartedAt  int64        `json:"startedAt"`
	UpdatedAt  int64        `json:"updatedAt"`
	// TranscriptPath is the absolute path of the Claude Code JSONL (empty if there is none).
	TranscriptPath string `json:"transcriptPath"`
	// Recap is a short phrase (generated by the mod with Haiku) about what the session is working on.
	Recap string `json:"recap"`
	// RepoURL and Branch are sent by the mod; ProjectID is computed by the hub (machine
	// checkout and root) and whatever the mod sends is never trusted.
	RepoURL   string `json:"repoUrl"`
	Branch    string `json:"branch"`
	ProjectID string `json:"projectId"`
	// LaunchReq is the QUORUM_LAUNCH_REQ the session was launched with (empty if Quorum did not launch it).
	LaunchReq string `json:"launchReq"`
	// HerdrPane and HerdrWorkspace identify the herdr pane it runs in (empty outside herdr).
	HerdrPane      string `json:"herdrPane"`
	HerdrWorkspace string `json:"herdrWorkspace"`
	// Account is the whoas alias the session runs under (or "default"). AccountKey is the first
	// 16 hex of sha256("quorum-account:" + email-or-org); the email and org id themselves are never sent
	// (empty when the identity is unavailable: the hub then falls back to machine/alias).
	Account    string `json:"account"`
	AccountKey string `json:"accountKey"`
	// ConfigDir is the Claude config dir the session uses.
	ConfigDir string `json:"configDir"`
	// Plugins lists the enabled better-claude plugins (subset of after, time-machine, use-haiku,
	// think-hard, image-preview, quick-peek).
	Plugins []string `json:"plugins"`
	// ContextEstimate is true when ContextPct is estimated rather than reported by Claude Code.
	ContextEstimate bool `json:"contextEstimate"`
	// Tokens are the session totals, RateLimits the last reported windows (reported at most once per 30 s).
	Tokens     TokenCount  `json:"tokens"`
	RateLimits []RateLimit `json:"rateLimits"`
	// UsageAt is when RateLimits were measured (Unix ms, 0 when never). Every update re-sends the last
	// RateLimits, so the hub saves them only when UsageAt is newer than what it has.
	UsageAt int64 `json:"usageAt"`
	// ImagesDir is the folder Claude Code stores this session's pasted images in
	// (`<tmp>/claude-<uid>/<project dashed>/<id>/images`; empty when unknown). The hub only
	// serves single image files from it, and only when its shape matches this session.
	ImagesDir string `json:"imagesDir"`
	// Background is what was left pending when the last main turn ended (zero when nothing).
	Background BackgroundInfo `json:"background"`
	// Effort is the reasoning effort of the last main turn (the Stop hook's effort.level), or the one a
	// device just set with /effort; empty until known or on a model without effort.
	Effort string `json:"effort"`
	// ModelOptions are the models /model takes in this session (the /config Model row's options, labelled
	// by the mod), EffortOptions the effort levels /effort takes. Both empty with an older mod.
	ModelOptions  []ModelOption `json:"modelOptions"`
	EffortOptions []string      `json:"effortOptions"`
	// Unread is computed by the hub (whatever the mod sends is ignored): the session is idle and its
	// last turn_end is newer than its seen mark ("done, unread"). background/working/needs_you/closed never are.
	Unread bool `json:"unread"`
}

// ModelOption is one model /model takes: Value is what is sent (`/model <value>`).
type ModelOption struct {
	Value       string `json:"value"`
	Label       string `json:"label"`
	Description string `json:"description"`
}

// SessionCommand is one slash command a session can run, as its mod reports it ($.command.list()).
// Source is Claude Code's (builtin|plugin|user|mcp); Group is how the app lists it
// (session|skill|plugin|mcp). TerminalOnly: an interactive built-in (picker, dialog, pane) a
// device may not run. Some commands are terminal-only only without arguments (bare /model,
// /after, /timeline): that is decided when one runs, not by this flag.
type SessionCommand struct {
	Name         string `json:"name"`
	Description  string `json:"description"`
	Source       string `json:"source"`
	Plugin       string `json:"plugin"`
	Group        string `json:"group"`
	TerminalOnly bool   `json:"terminalOnly"`
}

// SessionCommands is the payload of session_commands (daemon->hub) and of the mod's
// POST /v1/sessions/{id}/commands. Hash identifies the list: the mod re-sends it only when it changes.
type SessionCommands struct {
	Session  string           `json:"session"`
	Commands []SessionCommand `json:"commands"`
	Hash     string           `json:"hash"`
}

// CommandEvent is the data of a `command` event: a slash command a device ran in the session.
// Status queued (a turn was running: it runs when the turn ends), then done or failed. Text is the
// command's output (at most 8,000 chars), Error the English reason it failed.
type CommandEvent struct {
	ID     string `json:"id"`
	Name   string `json:"name"`
	Args   string `json:"args"`
	Origin string `json:"origin"` // device
	Status string `json:"status"` // queued|done|failed
	Text   string `json:"text,omitempty"`
	Error  string `json:"error,omitempty"`
}

// BackgroundInfo is a session's pending background work: Tasks live background tasks and
// subagents, WakeAt the next scheduled wake-up in Unix ms (0 = none).
type BackgroundInfo struct {
	Tasks  int   `json:"tasks"`
	WakeAt int64 `json:"wakeAt"`
}

// TokenCount sums token usage: In is uncached input, Out is output, Cache is cache read plus creation.
type TokenCount struct {
	In    int `json:"in"`
	Out   int `json:"out"`
	Cache int `json:"cache"`
}

// RateLimit is one rate-limit window: Kind is "five_hour" or "seven_day"; ResetsAt is ISO 8601 (may be empty).
type RateLimit struct {
	Kind        string  `json:"kind"`
	PercentUsed float64 `json:"percentUsed"`
	ResetsAt    string  `json:"resetsAt"`
}

// UsageWindow is one subscription window of an account: Pct 0-100, ResetsAt ISO 8601 (may be empty).
type UsageWindow struct {
	Pct      float64 `json:"pct"`
	ResetsAt string  `json:"resetsAt"`
}

// AccountUsage is the subscription usage of one Claude account (shared by every session and machine
// on it). Key is the accountKey, or machine + "/" + alias when the account identity is unavailable.
// At is the report time in Unix milliseconds.
type AccountUsage struct {
	Key      string      `json:"key"`
	Alias    string      `json:"alias"`
	FiveHour UsageWindow `json:"fiveHour"`
	SevenDay UsageWindow `json:"sevenDay"`
	At       int64       `json:"at"`
}

// Attention is the payload of an attention envelope: Kind is "needs_you" or "done", At Unix ms.
type Attention struct {
	Session string `json:"session"`
	Kind    string `json:"kind"`
	At      int64  `json:"at"`
}

type EventKind string

const (
	// KindUser data: {text, images?, command?, device?}. device is true when the prompt was sent from a
	// Quorum device (or is the turn of a slash command a device ran); without it the prompt was typed
	// in the terminal and the hub marks the session seen. command {name, args}: the turn of a slash
	// command (text is then "/name args").
	KindUser           EventKind = "user"
	KindAssistantDelta EventKind = "assistant_delta"
	KindAssistant      EventKind = "assistant"
	KindThinking       EventKind = "thinking"
	KindToolStart      EventKind = "tool_start"
	KindToolEnd        EventKind = "tool_end"
	KindAsk            EventKind = "ask"
	KindAskResolved    EventKind = "ask_resolved"
	KindTurnStart      EventKind = "turn_start"
	// KindTurnEnd data: {answer, reason, outputTokens, tokens: TokenCount, model: string, background: BackgroundInfo,
	// stopped?: true when the person pressed Stop in Claude Code on this turn (it ended "aborted"): never unread}.
	KindTurnEnd    EventKind = "turn_end"
	KindStatus     EventKind = "status"
	KindAgentStart EventKind = "agent_start"
	KindAgentEnd   EventKind = "agent_end"
	KindInfo       EventKind = "info"
	// KindTicket is emitted by the mod with /quorum ticket <id>: data {ticket:"<externalId>"}; empty = unlink.
	KindTicket EventKind = "ticket"
	// KindCommand data: CommandEvent; one per status change of a slash command run from a device.
	KindCommand EventKind = "command"
)

type Event struct {
	Seq     int64           `json:"seq"`
	Session string          `json:"session"`
	TS      int64           `json:"ts"`
	Kind    EventKind       `json:"kind"`
	Data    json.RawMessage `json:"data"`
}

