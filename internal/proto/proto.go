// Command is an order addressed to a session.
type Command struct {
	Type     string            `json:"type"` // prompt|decide|abort|close
	Text     string            `json:"text"`
	Mode     string            `json:"mode"` // now|queue|interrupt
	AskID    string            `json:"askId"`
	Decision string            `json:"decision"` // allow|deny
	Reason   string            `json:"reason"`
	Answers  map[string]string `json:"answers"`
}

// Envelope is the WS wrapper daemon<->hub and hub<->app.
// Type: hello|session_upsert|session_gone|session_removed|event|events|command|launch|launch_result|machine_status|backfill|backfill_result|ack|project_upsert|tickets|session_ticket|proposal_upsert|workspace_upsert|workspace_gone|project_gone
// session_gone (hub->app): the session was closed (state closed). session_removed (hub->app): the session closed without ever receiving a user prompt and was deleted; Envelope.Session is the id.
// workspace_upsert|workspace_gone (hub->app): Payload Workspace (for gone only the id matters); the initial snapshot carries one workspace_upsert per workspace.
// project_gone (hub->app): Payload {id}.
// proposal_upsert (hub->app): Payload Proposal, on every creation or change.
// project_upsert (hub->app): Payload Project (without token); the initial snapshot carries one per project and it is emitted on create, edit or sync.
// tickets (hub->app): Payload {projectId, tickets: []Ticket}, after a successful sync.
// session_ticket (hub->app): Payload {sessionId, ticketId, confirmed, removed?} when a link is suggested, confirmed or unlinked.
// events (hub->app): Payload []Event of a session (backfilled history, in a single envelope).
// caps (daemon->hub): Payload MachineCaps; the hub stores it and republishes machine_status.
// rpc / rpc_result (hub<->daemon): Payload RPC / RPCResult; request and response correlated by reqId.
// term_frame (daemon->hub->app): Payload TermFrame; a pane's screen, only while someone is watching, never stored.
// launch_session (hub->app): Payload {reqId, sessionId}; the launched session has registered and the app can navigate to it.
type Envelope struct {
	Type    string          `json:"type"`
	Machine string          `json:"machine"`
	Session string          `json:"session"`
	Payload json.RawMessage `json:"payload"`
}

type MachineHello struct {
	Machine  string        `json:"machine"`
	OS       string        `json:"os"`
	Env      string        `json:"env"` // linux|wsl|windows|darwin
	Version  string        `json:"version"`
	Sessions []SessionInfo `json:"sessions"`
	Caps     MachineCaps   `json:"caps"`
}

// MachineCaps are the capabilities of a machine that the daemon reports to the hub.
type MachineCaps struct {
	Herdr    bool `json:"herdr"`
	Terminal bool `json:"terminal"`
	Root     bool `json:"root"`
}

type LaunchRequest struct {
	ReqID          string `json:"reqId"`
	Dir            string `json:"dir"`
	Continue       bool   `json:"continue"`
	PermissionMode string `json:"permissionMode"`
	// Prompt is the first message of the session (optional); TicketID the originating ticket (used by the hub).
	Prompt   string `json:"prompt"`
	TicketID string `json:"ticketId"`
	// Resume is the id of the Claude session to resume (--resume).
	Resume string `json:"resume"`
	// Label is the project name, for the new workspace.
	Label string `json:"label"`
	Trust bool   `json:"trust"`
}

type LaunchResult struct {
	ReqID string `json:"reqId"`
	OK    bool   `json:"ok"`
	Error string `json:"error"`
	// Pane is the pane the session ended up in (if any); Via, the launcher used: herdr|tmux|wt|osascript.
	Pane string `json:"pane"`
	Via  string `json:"via"`
}

// Conversation is a Claude conversation saved on disk that can be resumed.
type Conversation struct {
	ID          string `json:"id"`
	Title       string `json:"title"`
	FirstPrompt string `json:"firstPrompt"`
	Messages    int    `json:"messages"`
	UpdatedAt   int64  `json:"updatedAt"`
	Open        bool   `json:"open"`
}

// RPC is a hub->daemon request; the response comes back as an RPCResult with the same ReqID.
type RPC struct {
	ReqID  string          `json:"reqId"`
	Method string          `json:"method"`
	Params json.RawMessage `json:"params"`
}

type RPCResult struct {
	ReqID  string          `json:"reqId"`
	Result json.RawMessage `json:"result"`
	Error  string          `json:"error"`
}

// TermFrame is the screen of a terminal pane.
type TermFrame struct {
	Pane   string `json:"pane"`
	Cols   int    `json:"cols"`
	Rows   int    `json:"rows"`
	ANSI   string `json:"ansi"`
	Closed bool   `json:"closed"`
}

// Workspace groups projects; WhoasProfile is the associated whoas profile.
type Workspace struct {
	ID           string `json:"id"`
	Name         string `json:"name"`
	Color        string `json:"color"`
	WhoasProfile string `json:"whoasProfile"`
}

type Progress struct {
	Done  int `json:"done"`
	Total int `json:"total"`
}

// ConnectorConfig: Kind = github|paperclip|exec|none. The token never travels; HasToken says whether one exists.
type ConnectorConfig struct {
	Kind        string            `json:"kind"`
	Settings    map[string]string `json:"settings"`
	HasToken    bool              `json:"hasToken"`
	IntervalMin int               `json:"intervalMin"`
}

type Project struct {
	ID          string          `json:"id"`
	WorkspaceID string          `json:"workspaceId"`
	Name        string          `json:"name"`
	RepoURL     string          `json:"repoUrl"`
	Connector   ConnectorConfig `json:"connector"`
	Summary     string          `json:"summary"`
	SummaryAt   int64           `json:"summaryAt"`
	Progress    Progress        `json:"progress"`
	SyncError   string          `json:"syncError"`
	SyncedAt    int64           `json:"syncedAt"`
}

type Checkout struct {
	ID        string `json:"id"`
	ProjectID string `json:"projectId"`
	Machine   string `json:"machine"`
	Root      string `json:"root"`
	RepoURL   string `json:"repoUrl"`
	Branch    string `json:"branch"`
	UpdatedAt int64  `json:"updatedAt"`
}

type TicketComment struct {
	Author string `json:"author"`
	Body   string `json:"body"`
	At     int64  `json:"at"`
}

// Ticket.Status is normalized: todo|in_progress|in_review|done|blocked; RawStatus is the source's own.
type Ticket struct {
	ID         string          `json:"id"`
	ProjectID  string          `json:"projectId"`
	ExternalID string          `json:"externalId"`
	Title      string          `json:"title"`
	Status     string          `json:"status"`
	RawStatus  string          `json:"rawStatus"`
	Assignee   string          `json:"assignee"`
	URL        string          `json:"url"`
	Body       string          `json:"body"`
	Comments   []TicketComment `json:"comments"`
	UpdatedAt  int64           `json:"updatedAt"`
}

type SessionTicket struct {
	SessionID string `json:"sessionId"`
	TicketID  string `json:"ticketId"`
	Confirmed bool   `json:"confirmed"`
	Removed   bool   `json:"removed,omitempty"`
}

// Proposal: Kind = comment|status (for status, Body is the target normalized status); Status = pending|sending|approved|rejected|failed.
type Proposal struct {
	ID        string `json:"id"`
	TicketID  string `json:"ticketId"`
	Kind      string `json:"kind"`
	Body      string `json:"body"`
	Status    string `json:"status"`
	Error     string `json:"error"`
	CreatedAt int64  `json:"createdAt"`
}
